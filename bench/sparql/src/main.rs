//! Tier-2 benchmark (graph / SPARQL): BSBM explore queries on dqaDB vs Oxigraph. Both
//! evaluate SPARQL with the same engine (spareval 0.2.9); what differs is storage,
//! indexes and the dataset layer.
//!
//! Modes:
//!   bsbm-schema <data.nt> <out.linkml.yaml>     product-type classes from the data
//!   dq-load <data.nt> <schema dir> <kb dir>      fresh dqaDB KB with the schema, timed import
//!   ox-load <data.nt> <store dir>                fresh Oxigraph store, timed bulk load
//!   run dqadb|oxigraph <dir> <mix.tsv.zst> <out.jsonl> [max queries]
//!                                                the queries of a BSBM mix in order, one client
//!   compare <a.jsonl> <b.jsonl>                  per-query result equality (by value)

use std::collections::BTreeMap;
use std::hash::{Hash, Hasher};
use std::io::{BufRead, BufReader, Write};
use std::path::{Path, PathBuf};
use std::time::Instant;

use oxrdf::{NamedOrBlankNode, Term, Triple};
use oxrdfio::{RdfFormat, RdfParser};

const BSBM: &str = "http://www4.wiwiss.fu-berlin.de/bizer/bsbm/v01/vocabulary/";
const INST: &str = "http://www4.wiwiss.fu-berlin.de/bizer/bsbm/v01/instances/";
const RDF_TYPE: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type";
const SUBCLASS: &str = "http://www.w3.org/2000/01/rdf-schema#subClassOf";
const XSD: &str = "http://www.w3.org/2001/XMLSchema#";

/// BSBM product types are data: `inst:ProductTypeN a bsbm:ProductType ; rdfs:subClassOf
/// inst:ProductTypeM`, and products are typed with them. dqaDB's ontology is closed, so
/// each one becomes a LinkML class (is_a = its rdfs:subClassOf).
fn bsbm_schema(data: &Path, out: &Path) {
    let reader = BufReader::new(std::fs::File::open(data).unwrap());
    let mut types: BTreeMap<String, Option<String>> = BTreeMap::new();
    for q in RdfParser::from_format(RdfFormat::NTriples).for_reader(reader) {
        let q = q.unwrap();
        let NamedOrBlankNode::NamedNode(s) = &q.subject else {
            continue;
        };
        match (q.predicate.as_str(), &q.object) {
            (RDF_TYPE, Term::NamedNode(o)) if o.as_str() == format!("{BSBM}ProductType") => {
                types.entry(s.as_str().to_string()).or_default();
            }
            (SUBCLASS, Term::NamedNode(o)) => {
                types.insert(s.as_str().to_string(), Some(o.as_str().to_string()));
            }
            _ => {}
        }
    }
    let name = |iri: &str| iri.strip_prefix(INST).unwrap_or(iri).replace('/', "_");
    let mut y = String::from(
        "# Generated by bench/sparql `bsbm-schema` from the BSBM data: one class per product type.\n\
         id: http://www4.wiwiss.fu-berlin.de/bizer/bsbm/v01/instances/\n\
         name: bsbm_product_types\n\
         prefixes:\n  bsbm-inst: http://www4.wiwiss.fu-berlin.de/bizer/bsbm/v01/instances/\n\
         default_prefix: bsbm-inst\n\
         classes:\n",
    );
    for (iri, parent) in &types {
        y += &format!("  {}:\n    class_uri: bsbm-inst:{}\n", name(iri), name(iri));
        if let Some(p) = parent {
            y += &format!("    is_a: {}\n", name(p));
        }
    }
    std::fs::File::create(out)
        .unwrap()
        .write_all(y.as_bytes())
        .unwrap();
    eprintln!("{} product types -> {}", types.len(), out.display());
}

fn dir_mb(p: &Path) -> f64 {
    fn walk(p: &Path) -> u64 {
        let Ok(rd) = std::fs::read_dir(p) else {
            return std::fs::metadata(p).map(|m| m.len()).unwrap_or(0);
        };
        rd.flatten()
            .map(|e| {
                let m = e.metadata().unwrap();
                if m.is_dir() { walk(&e.path()) } else { m.len() }
            })
            .sum()
    }
    walk(p) as f64 / 1e6
}

fn peak_rss_mb() -> f64 {
    std::fs::read_to_string("/proc/self/status")
        .ok()
        .and_then(|s| {
            s.lines().find(|l| l.starts_with("VmHWM:")).and_then(|l| {
                l.split_whitespace()
                    .nth(1)
                    .and_then(|v| v.parse::<f64>().ok())
            })
        })
        .unwrap_or(0.0)
        / 1024.0
}

fn dq_load(data: &Path, schema: &Path, kb_dir: &Path) {
    use dqadb_core::{Kb, WriteOpts, import::ImportOpts};
    let _ = std::fs::remove_dir_all(kb_dir);
    std::fs::create_dir_all(kb_dir).unwrap();
    Kb::init(kb_dir, "urn:dqadb:").unwrap();
    let onto = kb_dir.join("ontology");
    std::fs::remove_file(onto.join("schema.linkml.yaml")).unwrap();
    for e in std::fs::read_dir(schema).unwrap().flatten() {
        let name = e.file_name().to_string_lossy().to_string();
        let to = if name == "bsbm.linkml.yaml" {
            "schema.linkml.yaml".to_string()
        } else {
            name
        };
        std::fs::copy(e.path(), onto.join(to)).unwrap();
    }
    let kb = Kb::open(kb_dir).unwrap();
    kb.build_ontology(true).unwrap();
    let t = Instant::now();
    let write = WriteOpts {
        actor: "system:bench".into(),
        ..Default::default()
    };
    let r = kb
        .import(data, &ImportOpts::default(), &write, &mut |_, _| {})
        .unwrap();
    assert!(r.issues.is_empty(), "{:?}", r.issues);
    let secs = t.elapsed().as_secs_f64();
    println!(
        "dqaDB load: {} triples in {secs:.1}s ({:.0} triples/s), {} events; disk {:.0} MB (index {:.0} MB); peak RSS {:.0} MB",
        r.triples,
        r.triples as f64 / secs,
        r.events.len(),
        dir_mb(kb_dir),
        dir_mb(&kb_dir.join(".dqadb")),
        peak_rss_mb()
    );
}

fn ox_load(data: &Path, dir: &Path) {
    let _ = std::fs::remove_dir_all(dir);
    let store = oxigraph::store::Store::open(dir).unwrap();
    let t = Instant::now();
    let mut loader = store.bulk_loader();
    loader
        .load_from_reader(RdfFormat::NTriples, std::fs::File::open(data).unwrap())
        .unwrap();
    loader.commit().unwrap();
    store.flush().unwrap();
    let secs = t.elapsed().as_secs_f64();
    let n = store.len().unwrap();
    drop(store);
    println!(
        "Oxigraph load: {n} triples in {secs:.1}s ({:.0} triples/s); disk {:.0} MB; peak RSS {:.0} MB",
        n as f64 / secs,
        dir_mb(dir),
        peak_rss_mb()
    );
}

/// Query lines of a BSBM mix file (`query\t<sparql>` / `update\t<sparql>`).
fn mix_queries(path: &Path) -> Vec<String> {
    let r = BufReader::new(zstd::Decoder::new(std::fs::File::open(path).unwrap()).unwrap());
    r.lines()
        .map(|l| l.unwrap())
        .filter_map(|l| l.strip_prefix("query\t").map(str::to_string))
        .collect()
}

/// BSBM query template: the text without prefixes, IRIs, literals and numbers.
fn template(q: &str) -> String {
    let mut out = String::new();
    let mut chars = q.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '<' => {
                for d in chars.by_ref() {
                    if d == '>' {
                        break;
                    }
                }
                out.push_str("<>");
            }
            '"' => {
                for d in chars.by_ref() {
                    if d == '"' {
                        break;
                    }
                }
                out.push_str("\"\"");
            }
            c if c.is_ascii_digit() => {
                while chars
                    .peek()
                    .is_some_and(|d| d.is_ascii_digit() || *d == '.')
                {
                    chars.next();
                }
                out.push('0');
            }
            c if c.is_whitespace() => {
                if !out.ends_with(' ') {
                    out.push(' ');
                }
            }
            c => out.push(c),
        }
    }
    // drop the PREFIX declarations
    let start = ["SELECT", "DESCRIBE", "CONSTRUCT", "ASK"]
        .iter()
        .filter_map(|k| out.find(k))
        .min()
        .unwrap_or(0);
    out[start..].trim().to_string()
}

/// A term compared by value: numbers (any numeric XSD type or a decimal-based schema
/// type such as bsbm:USD) as numbers, everything else as its lexical form.
fn canon(t: &Term) -> String {
    match t {
        Term::NamedNode(n) => format!("<{}>", n.as_str()),
        Term::BlankNode(_) => "_:b".into(),
        Term::Literal(l) => {
            let dt = l.datatype().as_str();
            let numeric = dt.strip_prefix(XSD).is_some_and(|x| {
                matches!(
                    x,
                    "integer" | "decimal" | "double" | "float" | "int" | "long"
                )
            }) || dt.ends_with("/USD");
            if numeric && let Ok(v) = l.value().parse::<f64>() {
                return format!("{v}");
            }
            match l.language() {
                Some(lang) => format!("{}@{lang}", l.value()),
                None => l.value().to_string(),
            }
        }
        #[allow(unreachable_patterns)]
        _ => t.to_string(),
    }
}

enum Out {
    Rows(Vec<Vec<Option<Term>>>),
    Triples(Vec<Triple>),
    Bool(bool),
}

fn canon_out(o: &Out) -> Vec<String> {
    let mut v: Vec<String> = match o {
        Out::Rows(rows) => rows
            .iter()
            .map(|r| {
                r.iter()
                    .map(|t| t.as_ref().map(canon).unwrap_or_default())
                    .collect::<Vec<_>>()
                    .join("\t")
            })
            .collect(),
        Out::Triples(ts) => ts
            .iter()
            .map(|t| {
                format!(
                    "{} <{}> {}",
                    canon(&t.subject.clone().into()),
                    t.predicate.as_str(),
                    canon(&t.object)
                )
            })
            .collect(),
        Out::Bool(b) => vec![b.to_string()],
    };
    v.sort();
    v
}

trait System {
    fn run(&self, q: &str) -> Out;
}

struct Dq(dqadb_core::Kb);
impl System for Dq {
    fn run(&self, q: &str) -> Out {
        use dqadb_core::sparql::{Answer, Limits};
        let limits = Limits {
            rows: usize::MAX,
            timeout: std::time::Duration::from_secs(600),
        };
        match self.0.query(q, &limits).unwrap() {
            Answer::Solutions { rows, .. } => Out::Rows(rows),
            Answer::Graph { triples, .. } => Out::Triples(triples),
            Answer::Boolean(b) => Out::Bool(b),
        }
    }
}

struct Ox(oxigraph::store::Store);
impl System for Ox {
    fn run(&self, q: &str) -> Out {
        use oxigraph::sparql::{QueryResults, SparqlEvaluator};
        match SparqlEvaluator::new()
            .parse_query(q)
            .unwrap()
            .on_store(&self.0)
            .execute()
            .unwrap()
        {
            QueryResults::Solutions(s) => {
                let vars: Vec<_> = s.variables().to_vec();
                Out::Rows(
                    s.map(|r| {
                        let r = r.unwrap();
                        vars.iter().map(|v| r.get(v).cloned()).collect()
                    })
                    .collect(),
                )
            }
            QueryResults::Graph(g) => Out::Triples(g.map(|t| t.unwrap()).collect()),
            QueryResults::Boolean(b) => Out::Bool(b),
        }
    }
}

fn run(system: &str, dir: &Path, mix: &Path, out: &Path, max: Option<usize>) {
    let mut queries = mix_queries(mix);
    if let Some(m) = max {
        queries.truncate(m);
    }
    let sys: Box<dyn System> = match system {
        "dqadb" => Box::new(Dq(dqadb_core::Kb::open(dir).unwrap())),
        "oxigraph" => Box::new(Ox(oxigraph::store::Store::open(dir).unwrap())),
        other => panic!("unknown system {other}"),
    };
    let mut templates: BTreeMap<String, usize> = BTreeMap::new();
    let mut per_t: BTreeMap<usize, (usize, f64, usize)> = BTreeMap::new(); // count, secs, empty
    let mut f = std::io::BufWriter::new(std::fs::File::create(out).unwrap());
    let started = Instant::now();
    let mut total = 0.0;
    for (i, q) in queries.iter().enumerate() {
        let next = templates.len() + 1;
        let tid = *templates.entry(template(q)).or_insert(next);
        let t = Instant::now();
        let o = sys.run(q);
        let secs = t.elapsed().as_secs_f64();
        total += secs;
        let rows = canon_out(&o);
        let mut h = std::collections::hash_map::DefaultHasher::new();
        rows.hash(&mut h);
        let e = per_t.entry(tid).or_default();
        e.0 += 1;
        e.1 += secs;
        e.2 += rows.is_empty() as usize;
        writeln!(
            f,
            "{}",
            serde_json::json!({"i": i, "t": tid, "ms": secs * 1e3, "n": rows.len(), "hash": format!("{:016x}", h.finish()), "head": rows.iter().take(3).collect::<Vec<_>>()})
        )
        .unwrap();
        if (i + 1) % 1000 == 0 {
            eprintln!(
                "  {} queries, {:.0} s",
                i + 1,
                started.elapsed().as_secs_f64()
            );
        }
    }
    let n = queries.len();
    println!(
        "{system}: {n} queries in {total:.1}s ({:.1} queries/s); peak RSS {:.0} MB",
        n as f64 / total,
        peak_rss_mb()
    );
    let mut by_id: Vec<(&String, &usize)> = templates.iter().collect();
    by_id.sort_by_key(|(_, id)| **id);
    for (tpl, id) in by_id {
        let (c, s, e) = per_t[id];
        println!(
            "  T{id:<2} n={c:<5} mean {:7.2} ms  empty {:3.0}%  {}",
            s * 1e3 / c as f64,
            100.0 * e as f64 / c as f64,
            tpl.chars().take(70).collect::<String>()
        );
    }
}

fn compare(a: &Path, b: &Path) {
    let read = |p: &Path| -> Vec<serde_json::Value> {
        BufReader::new(std::fs::File::open(p).unwrap())
            .lines()
            .map(|l| serde_json::from_str(&l.unwrap()).unwrap())
            .collect()
    };
    let (a, b) = (read(a), read(b));
    let mut diff: BTreeMap<u64, Vec<u64>> = BTreeMap::new();
    for (x, y) in a.iter().zip(&b) {
        if x["hash"] != y["hash"] {
            diff.entry(x["t"].as_u64().unwrap())
                .or_default()
                .push(x["i"].as_u64().unwrap());
        }
    }
    println!(
        "{} queries compared, {} differ",
        a.len().min(b.len()),
        diff.values().map(Vec::len).sum::<usize>()
    );
    for (t, is) in &diff {
        let i = is[0] as usize;
        println!(
            "  T{t}: {} differ, e.g. query {i}: n {} vs {}\n    a {}\n    b {}",
            is.len(),
            a[i]["n"],
            b[i]["n"],
            a[i]["head"],
            b[i]["head"]
        );
    }
}

/// Calls the engine makes into dqaDB's dataset for the queries of one template, and the
/// time spent in each kind of call.
mod counting {
    use dqadb_core::sparql::{DTerm, KbDataset};
    use spareval::{InternalQuad, QueryableDataset};
    use std::cell::RefCell;
    use std::time::Instant;

    #[derive(Default, Debug)]
    pub struct Stats {
        pub patterns: usize,
        pub quads: usize,
        pub pattern_s: f64,
        pub internalize: usize,
        pub internalize_s: f64,
        pub externalize: usize,
        pub externalize_s: f64,
        pub expr: usize,
        pub expr_s: f64,
    }

    #[derive(Clone, Copy)]
    pub struct Counting<'a> {
        pub inner: KbDataset<'a>,
        pub stats: &'a RefCell<Stats>,
    }

    impl<'a> QueryableDataset<'a> for Counting<'a> {
        type InternalTerm = DTerm;
        type Error = dqadb_core::Error;
        fn internal_quads_for_pattern(
            &self,
            s: Option<&DTerm>,
            p: Option<&DTerm>,
            o: Option<&DTerm>,
            g: Option<Option<&DTerm>>,
        ) -> impl Iterator<Item = Result<InternalQuad<DTerm>, Self::Error>> + use<'a> {
            let t = Instant::now();
            let v: Vec<_> = self.inner.internal_quads_for_pattern(s, p, o, g).collect();
            let mut st = self.stats.borrow_mut();
            st.patterns += 1;
            st.quads += v.len();
            st.pattern_s += t.elapsed().as_secs_f64();
            v.into_iter()
        }
        fn internalize_term(&self, term: oxrdf::Term) -> Result<DTerm, Self::Error> {
            let t = Instant::now();
            let r = self.inner.internalize_term(term);
            let mut st = self.stats.borrow_mut();
            st.internalize += 1;
            st.internalize_s += t.elapsed().as_secs_f64();
            r
        }
        fn externalize_term(&self, term: DTerm) -> Result<oxrdf::Term, Self::Error> {
            let t = Instant::now();
            let r = self.inner.externalize_term(term);
            let mut st = self.stats.borrow_mut();
            st.externalize += 1;
            st.externalize_s += t.elapsed().as_secs_f64();
            r
        }
        fn externalize_expression_term(
            &self,
            term: DTerm,
        ) -> Result<spareval::ExpressionTerm, Self::Error> {
            let t = Instant::now();
            let r = self.inner.externalize_expression_term(term);
            let mut st = self.stats.borrow_mut();
            st.expr += 1;
            st.expr_s += t.elapsed().as_secs_f64();
            r
        }
    }
}

fn profile(dq: &Path, mix: &Path, template_id: usize) {
    use spareval::{QueryEvaluator, QueryResults};
    let kb = dqadb_core::Kb::open(dq).unwrap();
    let store = dqadb_core::store::Store::open(&kb.index_dir().join("index.sqlite")).unwrap();
    let r = store.read().unwrap();
    let ns = kb.event_namespace();
    let ev = kb.events_dir();
    let mut templates: BTreeMap<String, usize> = BTreeMap::new();
    let stats = std::cell::RefCell::new(counting::Stats::default());
    let (mut n, mut total) = (0, 0.0);
    for q in mix_queries(mix) {
        let next = templates.len() + 1;
        if *templates.entry(template(&q)).or_insert(next) != template_id {
            continue;
        }
        let parsed = spargebra::SparqlParser::new().parse_query(&q).unwrap();
        let cache = dqadb_core::sparql::TermCache::default();
        let ds = counting::Counting {
            inner: dqadb_core::sparql::KbDataset::new(&r, &ns, &ev, &cache),
            stats: &stats,
        };
        let t = Instant::now();
        let ev = QueryEvaluator::new();
        match ev.prepare(&parsed).execute(ds).unwrap() {
            QueryResults::Solutions(s) => {
                s.for_each(|x| {
                    x.unwrap();
                });
            }
            QueryResults::Graph(g) => {
                g.for_each(|x| {
                    x.unwrap();
                });
            }
            QueryResults::Boolean(_) => {}
        }
        total += t.elapsed().as_secs_f64();
        n += 1;
    }
    let st = stats.borrow();
    let per = |x: f64| x * 1e3 / n as f64;
    println!("T{template_id}: {n} queries, {:.2} ms/query", per(total));
    println!(
        "  pattern lookups {:.0}/query ({:.0} quads) {:.2} ms",
        st.patterns as f64 / n as f64,
        st.quads as f64 / n as f64,
        per(st.pattern_s)
    );
    println!(
        "  internalize {:.0}/query {:.2} ms; externalize {:.0}/query {:.2} ms; expression terms {:.0}/query {:.2} ms",
        st.internalize as f64 / n as f64,
        per(st.internalize_s),
        st.externalize as f64 / n as f64,
        per(st.externalize_s),
        st.expr as f64 / n as f64,
        per(st.expr_s)
    );
    println!(
        "  engine (the rest) {:.2} ms",
        per(total - st.pattern_s - st.internalize_s - st.externalize_s - st.expr_s)
    );
}

/// SQLite insert cost of the pos/osp permutations for 3.5M BSBM-like triples in batches
/// of 50k: in file order vs sorted per batch (same pragmas as the dqaDB index).
fn insert_order(dir: &Path) {
    let n = 3_500_000u64;
    let batch = 50_000usize;
    let mut seed = 7u64;
    let mut rnd = move || {
        seed ^= seed << 13;
        seed ^= seed >> 7;
        seed ^= seed << 17;
        seed
    };
    // subjects in file order, ~12 triples each; 40 predicates; objects: half shared
    // (types, features, producers), half unique literals
    let triples: Vec<(i64, i64, i64)> = (0..n)
        .map(|k| {
            let s = (k / 12) as i64 + 1;
            let p = (rnd() % 40) as i64 + 1_000_000_000;
            let o = if k % 2 == 0 {
                (rnd() % 20_000) as i64 + 2_000_000_000
            } else {
                3_000_000_000 + k as i64
            };
            (s, p, o)
        })
        .collect();
    for sorted in [false, true] {
        let path = dir.join(format!("order-{sorted}.sqlite"));
        let _ = std::fs::remove_file(&path);
        let _ = std::fs::remove_file(path.with_extension("sqlite-wal"));
        let conn = rusqlite::Connection::open(&path).unwrap();
        conn.execute_batch("PRAGMA page_size=16384; PRAGMA journal_mode=WAL; PRAGMA synchronous=NORMAL; PRAGMA cache_size=-65536;
            CREATE TABLE pos(a INTEGER NOT NULL, b INTEGER NOT NULL, c INTEGER NOT NULL, PRIMARY KEY(a,b,c)) WITHOUT ROWID;
            CREATE TABLE osp(a INTEGER NOT NULL, b INTEGER NOT NULL, c INTEGER NOT NULL, PRIMARY KEY(a,b,c)) WITHOUT ROWID;").unwrap();
        let t = Instant::now();
        for chunk in triples.chunks(batch) {
            let mut pos: Vec<(i64, i64, i64)> = chunk.iter().map(|&(s, p, o)| (p, o, s)).collect();
            let mut osp: Vec<(i64, i64, i64)> = chunk.iter().map(|&(s, p, o)| (o, s, p)).collect();
            if sorted {
                pos.sort_unstable();
                osp.sort_unstable();
            }
            let tx = conn.unchecked_transaction().unwrap();
            {
                let mut a = tx
                    .prepare_cached("INSERT OR IGNORE INTO pos VALUES (?1, ?2, ?3)")
                    .unwrap();
                for r in &pos {
                    a.execute([r.0, r.1, r.2]).unwrap();
                }
                let mut b = tx
                    .prepare_cached("INSERT OR IGNORE INTO osp VALUES (?1, ?2, ?3)")
                    .unwrap();
                for r in &osp {
                    b.execute([r.0, r.1, r.2]).unwrap();
                }
            }
            tx.commit().unwrap();
        }
        println!(
            "sorted per batch {sorted}: {:.1} s for {n} triples x 2 tables",
            t.elapsed().as_secs_f64()
        );
        drop(conn);
        let _ = std::fs::remove_file(&path);
    }
}

/// Cost of one bound-subject, bound-predicate lookup (the pattern most BSBM joins do),
/// dqaDB's index scan vs Oxigraph's store, over every product's rdfs:label and
/// productPropertyNumeric1.
fn lookup(dq: &Path, ox: &Path) {
    use dqadb_core::rdf::Term as DqTerm;
    use oxigraph::model::{NamedNodeRef, TermRef};
    let kb = dqadb_core::Kb::open(dq).unwrap();
    let store = dqadb_core::store::Store::open(&kb.index_dir().join("index.sqlite")).unwrap();
    let r = store.read().unwrap();
    let oxs = oxigraph::store::Store::open(ox).unwrap();
    let product = format!("{BSBM}Product");
    let products: Vec<String> = oxs
        .quads_for_pattern(
            None,
            Some(NamedNodeRef::new(RDF_TYPE).unwrap()),
            Some(TermRef::NamedNode(NamedNodeRef::new(&product).unwrap())),
            None,
        )
        .map(|q| {
            q.unwrap()
                .subject
                .to_string()
                .trim_matches(|c| c == '<' || c == '>')
                .to_string()
        })
        .collect();
    let preds = [
        "http://www.w3.org/2000/01/rdf-schema#label".to_string(),
        format!("{BSBM}productPropertyNumeric1"),
    ];
    let ids: Vec<(u64, u64)> = products
        .iter()
        .flat_map(|s| preds.iter().map(move |p| (s, p)))
        .map(|(s, p)| {
            (
                r.term_id(&DqTerm::Iri(s.clone())).unwrap().unwrap(),
                r.term_id(&DqTerm::Iri(p.clone())).unwrap().unwrap(),
            )
        })
        .collect();
    let reps = 20;
    let t = Instant::now();
    let mut n = 0;
    for _ in 0..reps {
        for (s, p) in &ids {
            n += r.scan(Some(*s), Some(*p), None).count();
        }
    }
    let dq_us = t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64;
    let t = Instant::now();
    let mut m = 0;
    for _ in 0..reps {
        for s in &products {
            for p in &preds {
                m += oxs
                    .quads_for_pattern(
                        Some(NamedNodeRef::new(s).unwrap().into()),
                        Some(NamedNodeRef::new(p).unwrap()),
                        None,
                        None,
                    )
                    .count();
            }
        }
    }
    let ox_us = t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64;
    println!("(s, p, ?) lookup: dqaDB {dq_us:.1} us ({n} hits), Oxigraph {ox_us:.1} us ({m} hits)");
    let t = Instant::now();
    for _ in 0..reps {
        for (s, _) in &ids {
            r.term(*s).unwrap();
        }
    }
    // floor: the simplest SQLite point query on the same table, one prepared statement
    let conn = rusqlite::Connection::open_with_flags(
        kb.index_dir().join("index.sqlite"),
        rusqlite::OpenFlags::SQLITE_OPEN_READ_ONLY,
    )
    .unwrap();
    for sql in [
        "SELECT c FROM spo WHERE a = ?1 AND b = ?2",
        "SELECT a, b, c FROM spo WHERE a = ?1 AND b = ?2 ORDER BY a, b, c LIMIT 1024",
    ] {
        let mut st = conn.prepare(sql).unwrap();
        let t = Instant::now();
        let mut k = 0;
        for _ in 0..reps {
            for (s, p) in &ids {
                let mut rows = st.query([*s as i64, *p as i64]).unwrap();
                while let Some(_r) = rows.next().unwrap() {
                    k += 1;
                }
            }
        }
        println!(
            "raw SQLite {sql:70}: {:.1} us ({k})",
            t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64
        );
    }
    {
        let sql = "SELECT a, b, c FROM spo WHERE a = ?1 AND b = ?2 ORDER BY a, b, c LIMIT 1024";
        let t = Instant::now();
        let mut k = 0usize;
        for _ in 0..reps {
            for (s, p) in &ids {
                let args: Vec<i64> = vec![*s as i64, *p as i64];
                let mut st = conn.prepare_cached(sql).unwrap();
                let rows: Vec<(i64, i64, i64)> = st
                    .query_map(rusqlite::params_from_iter(args), |r| {
                        Ok((r.get(0)?, r.get(1)?, r.get(2)?))
                    })
                    .unwrap()
                    .collect::<Result<_, _>>()
                    .unwrap();
                k += rows.len();
            }
        }
        println!(
            "as page(): prepare_cached + params_from_iter + collect: {:.1} us ({k})",
            t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64
        );
        conn.execute_batch("BEGIN").unwrap();
        let t = Instant::now();
        for _ in 0..reps {
            for (s, p) in &ids {
                let mut st = conn.prepare_cached(sql).unwrap();
                let rows: Vec<(i64, i64, i64)> = st
                    .query_map([*s as i64, *p as i64], |r| {
                        Ok((r.get(0)?, r.get(1)?, r.get(2)?))
                    })
                    .unwrap()
                    .collect::<Result<_, _>>()
                    .unwrap();
                k += rows.len();
            }
        }
        println!(
            "same inside a read transaction: {:.1} us",
            t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64
        );
        conn.execute_batch("COMMIT").unwrap();
        conn.set_db_config(
            rusqlite::config::DbConfig::SQLITE_DBCONFIG_ENABLE_QPSG,
            true,
        )
        .unwrap();
        conn.flush_prepared_statement_cache();
        let t = Instant::now();
        for _ in 0..reps {
            for (s, p) in &ids {
                let mut st = conn.prepare_cached(sql).unwrap();
                let rows: Vec<(i64, i64, i64)> = st
                    .query_map([*s as i64, *p as i64], |r| {
                        Ok((r.get(0)?, r.get(1)?, r.get(2)?))
                    })
                    .unwrap()
                    .collect::<Result<_, _>>()
                    .unwrap();
                k += rows.len();
            }
        }
        println!(
            "as page() with QPSG on: {:.1} us",
            t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64
        );
        let t = Instant::now();
        for _ in 0..reps {
            for (s, p) in &ids {
                let mut st = conn.prepare_cached(sql).unwrap();
                let mut rows = st.query([*s as i64, *p as i64]).unwrap();
                while let Some(_r) = rows.next().unwrap() {
                    k += 1;
                }
            }
        }
        println!(
            "prepare_cached + query (no query_map): {:.1} us",
            t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64
        );
        let mut st = conn.prepare(sql).unwrap();
        let t = Instant::now();
        for _ in 0..reps {
            for (s, p) in &ids {
                let rows: Vec<(i64, i64, i64)> = st
                    .query_map([*s as i64, *p as i64], |r| {
                        Ok((r.get(0)?, r.get(1)?, r.get(2)?))
                    })
                    .unwrap()
                    .collect::<Result<_, _>>()
                    .unwrap();
                k += rows.len();
            }
        }
        let (s0, p0) = ids[0];
        let t = Instant::now();
        for _ in 0..(reps * ids.len()) {
            let mut st = conn.prepare_cached(sql).unwrap();
            let mut rows = st.query([s0 as i64, p0 as i64]).unwrap();
            while let Some(_r) = rows.next().unwrap() {}
        }
        println!(
            "prepare_cached + query, same params every time: {:.1} us",
            t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64
        );
        let opts: Vec<String> = conn
            .prepare("PRAGMA compile_options")
            .unwrap()
            .query_map([], |r| r.get(0))
            .unwrap()
            .map(|x| x.unwrap())
            .filter(|o: &String| o.contains("STAT"))
            .collect();
        println!("SQLite compile options with STAT: {opts:?}");
        let t = Instant::now();
        for _ in 0..(reps * ids.len()) {
            let _st = conn.prepare(sql).unwrap();
        }
        println!(
            "prepare() alone: {:.1} us",
            t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64
        );
        let t = Instant::now();
        for _ in 0..(reps * ids.len()) {
            let _st = conn.prepare_cached(sql).unwrap();
        }
        println!(
            "prepare_cached() alone: {:.1} us",
            t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64
        );
        println!(
            "prepared once + query_map + collect: {:.1} us",
            t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64
        );
    }
    println!(
        "term decode: dqaDB {:.1} us",
        t.elapsed().as_secs_f64() * 1e6 / (reps * ids.len()) as f64
    );
}

/// Fixed per-query costs of `Kb::query` on a KB, each step timed alone.
fn overhead(dir: &Path) {
    use dqadb_core::sparql::Limits;
    let kb = dqadb_core::Kb::open(dir).unwrap();
    let n = 200;
    let time = |name: &str, f: &dyn Fn()| {
        f();
        let t = Instant::now();
        for _ in 0..n {
            f();
        }
        println!(
            "{name:28} {:7.3} ms",
            t.elapsed().as_secs_f64() * 1e3 / n as f64
        );
    };
    time("Kb::ontology()", &|| {
        kb.ontology().unwrap();
    });
    time("ontology().inference()", &|| {
        kb.ontology().unwrap().inference();
    });
    time("event::head()", &|| {
        dqadb_core::event::head(&kb.events_dir()).unwrap();
    });
    let store = dqadb_core::store::Store::open(&kb.index_dir().join("index.sqlite")).unwrap();
    time("store.read() + watermark", &|| {
        let r = store.read().unwrap();
        r.watermark().unwrap();
        r.inference_hash().unwrap();
    });
    time("Kb::sync() (nothing new)", &|| {
        kb.sync().unwrap();
    });
    time("Kb::fingerprint()", &|| {
        kb.fingerprint().unwrap();
    });
    let q = "ASK { <urn:x> <urn:y> <urn:z> }";
    time("Kb::query(ASK, no match)", &|| {
        kb.query(q, &Limits::default()).unwrap();
    });
}

fn main() {
    let a: Vec<String> = std::env::args().collect();
    let p = |i: usize| PathBuf::from(&a[i]);
    match a.get(1).map(String::as_str) {
        Some("bsbm-schema") => bsbm_schema(&p(2), &p(3)),
        Some("dq-load") => dq_load(&p(2), &p(3), &p(4)),
        Some("ox-load") => ox_load(&p(2), &p(3)),
        Some("run") => run(
            &a[2],
            &p(3),
            &p(4),
            &p(5),
            a.get(6).map(|v| v.parse().unwrap()),
        ),
        Some("compare") => compare(&p(2), &p(3)),
        Some("overhead") => overhead(&p(2)),
        Some("lookup") => lookup(&p(2), &p(3)),
        Some("insert-order") => insert_order(&p(2)),
        Some("profile") => profile(&p(2), &p(3), a[4].parse().unwrap()),
        _ => {
            eprintln!("see the module docs for modes");
            std::process::exit(2);
        }
    }
}
