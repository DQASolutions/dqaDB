//! Tier-2 benchmark (graph / SPARQL): BSBM on dqaDB vs Oxigraph.
//!
//! Modes:
//!   bsbm-schema <data.nt> <out.linkml.yaml>   product-type classes from the data

use std::collections::BTreeMap;
use std::io::{BufReader, Write};
use std::path::{Path, PathBuf};

use oxrdf::{NamedOrBlankNode, Term};
use oxrdfio::{RdfFormat, RdfParser};

const BSBM: &str = "http://www4.wiwiss.fu-berlin.de/bizer/bsbm/v01/vocabulary/";
const INST: &str = "http://www4.wiwiss.fu-berlin.de/bizer/bsbm/v01/instances/";
const RDF_TYPE: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type";
const SUBCLASS: &str = "http://www.w3.org/2000/01/rdf-schema#subClassOf";

/// BSBM product types are data: `inst:ProductTypeN a bsbm:ProductType ; rdfs:subClassOf
/// inst:ProductTypeM`, and products are typed with them. dqaDB's ontology is closed, so
/// each one becomes a LinkML class (is_a = its rdfs:subClassOf).
fn bsbm_schema(data: &Path, out: &Path) {
    let reader = BufReader::new(std::fs::File::open(data).unwrap());
    let mut types: BTreeMap<String, Option<String>> = BTreeMap::new();
    for q in RdfParser::from_format(RdfFormat::NTriples).for_reader(reader) {
        let q = q.unwrap();
        let NamedOrBlankNode::NamedNode(s) = &q.subject else {
            continue;
        };
        match (q.predicate.as_str(), &q.object) {
            (RDF_TYPE, Term::NamedNode(o)) if o.as_str() == format!("{BSBM}ProductType") => {
                types.entry(s.as_str().to_string()).or_default();
            }
            (SUBCLASS, Term::NamedNode(o)) => {
                types.insert(s.as_str().to_string(), Some(o.as_str().to_string()));
            }
            _ => {}
        }
    }
    let name = |iri: &str| iri.strip_prefix(INST).unwrap_or(iri).replace('/', "_");
    let mut y = String::from(
        "# Generated by bench/sparql `bsbm-schema` from the BSBM data: one class per product type.\n\
         id: http://www4.wiwiss.fu-berlin.de/bizer/bsbm/v01/instances/\n\
         name: bsbm_product_types\n\
         prefixes:\n  bsbm-inst: http://www4.wiwiss.fu-berlin.de/bizer/bsbm/v01/instances/\n\
         default_prefix: bsbm-inst\n\
         classes:\n",
    );
    for (iri, parent) in &types {
        y += &format!("  {}:\n    class_uri: bsbm-inst:{}\n", name(iri), name(iri));
        if let Some(p) = parent {
            y += &format!("    is_a: {}\n", name(p));
        }
    }
    std::fs::File::create(out)
        .unwrap()
        .write_all(y.as_bytes())
        .unwrap();
    eprintln!("{} product types -> {}", types.len(), out.display());
}

fn main() {
    let a: Vec<String> = std::env::args().collect();
    match a.get(1).map(String::as_str) {
        Some("bsbm-schema") => bsbm_schema(&PathBuf::from(&a[2]), &PathBuf::from(&a[3])),
        _ => {
            eprintln!("usage: dqadb-bench-sparql bsbm-schema <data.nt> <out.linkml.yaml>");
            std::process::exit(2);
        }
    }
}
